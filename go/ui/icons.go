// drawIcon paints one commodity icon at x,y with a dim outline.
func drawIcon(fb *render.FB, x, y, idx int, bright bool) {
	if idx < 0 || idx >= len(commodityIcons) {
		return
	}
	ic := commodityIcons[idx]
	shade := 3
	if bright {
		shade = 5
	}
	col := render.Color(ic.ramp, shade)
	for ry, row := range ic.rows {
		for rx := 0; rx < len(row) && rx < 8; rx++ {
			if row[rx] == '#' || row[rx] == '+' {
				fb.Px(x+rx, y+ry, col)
			}
		}
	}
}
