package render

// Cyrillic glyphs for the 5x7 bitmap font. Letters that share a Latin shape
// (А В Е К М Н О Р С Т У Х) reuse it; the rest are drawn here.
func init() {
	ru := map[rune][7]uint8{
		'Б': {0x1F, 0x10, 0x1E, 0x11, 0x11, 0x11, 0x1E},
		'Г': {0x1F, 0x10, 0x10, 0x10, 0x10, 0x10, 0x10},
		'Д': {0x06, 0x0A, 0x0A, 0x0A, 0x0A, 0x1F, 0x11},
		'Ж': {0x15, 0x15, 0x15, 0x1F, 0x15, 0x15, 0x15},
		'З': {0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E},
		'И': {0x11, 0x11, 0x13, 0x15, 0x19, 0x11, 0x11},
		'Й': {0x0A, 0x11, 0x13, 0x15, 0x19, 0x11, 0x11},
		'Л': {0x07, 0x09, 0x09, 0x09, 0x09, 0x09, 0x11},
		'П': {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11},
		'Ф': {0x04, 0x0E, 0x15, 0x15, 0x15, 0x0E, 0x04},
		'Ц': {0x12, 0x12, 0x12, 0x12, 0x12, 0x1F, 0x01},
		'Ч': {0x11, 0x11, 0x11, 0x0F, 0x01, 0x01, 0x01},
		'Ш': {0x15, 0x15, 0x15, 0x15, 0x15, 0x15, 0x1F},
		'Щ': {0x15, 0x15, 0x15, 0x15, 0x15, 0x1F, 0x01},
		'Ъ': {0x18, 0x08, 0x0E, 0x09, 0x09, 0x09, 0x0E},
		'Ы': {0x11, 0x11, 0x1D, 0x13, 0x13, 0x11, 0x11},
		'Ь': {0x10, 0x10, 0x1E, 0x11, 0x11, 0x11, 0x1E},
		'Э': {0x0E, 0x11, 0x01, 0x07, 0x01, 0x11, 0x0E},
		'Ю': {0x11, 0x17, 0x15, 0x1D, 0x15, 0x17, 0x11},
		'Я': {0x0F, 0x11, 0x11, 0x0F, 0x05, 0x09, 0x11},
	}
	for r, gl := range ru {
		if _, exists := glyphs[r]; !exists {
			glyphs[r] = gl
		}
	}
	// Latin-shaped Cyrillic letters
	pairs := map[rune]rune{
		'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H',
		'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'У': 'Y', 'Х': 'X',
	}
	for ru2, lat := range pairs {
		if _, exists := glyphs[ru2]; !exists {
			glyphs[ru2] = glyphs[lat]
		}
	}
	glyphs['Ё'] = glyphs['Е']
}

// HasGlyph reports whether the bitmap font can render r.
func HasGlyph(r rune) bool {
	_, ok := glyphs[r]
	return ok
}
